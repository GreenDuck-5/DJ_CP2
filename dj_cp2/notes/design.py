#DJ, 1st, Design Notes


#What is top down design?
    # Plan first, code second


#What are the steps of top down design?
    # Begin with purpose of a projcet
    # Then break down project into to smaller pieces
    # Every smaller piece is unique


#What are the advantages of top down design?
    # Allows for specialized teams to take on tasks and collaborate
    # Makes sure you're not repeating code
    # Makes it easier to solve programming problems
    # Easy to track progress
    # Steps become simple
    # Reusable solutions


#What is bottom up design?
    # Build small parts, build up to project


#What are the steps of bottom up design
    # Build small parts
    # Add new parts as they are needed
    # All the small parts put together to final project


#What are the advantage of bottom up design?
    # Easy to test individual parts
    # Focus on developers problem solving
    # Increased modularity
    # Reusable sections of code
    # Less time in planning. more time programming


#When would it be a good idea to use bottom up design compared to top down design?
    # Bottom up is useful for smaller, more consise programs